// pairedBase and pairedHead model a responsibility boundary move: methods
// leave a large owner and arrive on a private hooks type.
func pairedTrees() (map[string]string, map[string]string) {
	base := map[string]string{
		"p/container.go": `package p

type Container struct{ a, b int }

func (*Container) One()   {}
func (*Container) Two()   {}
func (*Container) three() {}

type hooks struct{}

func (hooks) A() {}
func (hooks) B() {}

type Untouched struct{ x int }

func (Untouched) U() {}

type Handle struct{ h int }

func (Handle) Restore() {}

type Gone struct{}
`,
	}
	head := map[string]string{
		"p/container.go": `package p

type Container struct{ a, b int }

func (*Container) One()   {}
func (*Container) three() {}
`,
		// Untouched moves to another file at a different line: no row.
		"p/other.go": `package p

type hooks struct{}

func (hooks) A() {}
func (hooks) B() {}
func (hooks) C() {}
func (hooks) D() {}

// padding

type Untouched struct{ x int }

func (Untouched) U() {}

type Flag struct{ h int }

func (Flag) Reset() {}
`,
	}
	return base, head
}

func deltaOf(t *testing.T, base, head map[string]string, extra ...string) *deltaReport {
	t.Helper()
	b, h := writeTree(t, base), writeTree(t, head)
	args := append([]string{"delta", "-packages", "p", "-base-dir", b, "-head-dir", h}, extra...)
	out, err := runCLI(t, args...)
	if err != nil {
		t.Fatal(err)
	}
	var report deltaReport
	if err := json.Unmarshal([]byte(out), &report); err != nil {
		t.Fatal(err)
	}
	return &report
}

func TestDeltaKeepsBothSidesOfAResponsibilityBoundary(t *testing.T) {
	base, head := pairedTrees()
	report := deltaOf(t, base, head)
	rows := map[string]ownerDelta{}
	for _, row := range report.Owners {
		rows[row.Owner] = row
	}
	c := rows["p.Container"]
	if c.Status != "changed" || c.Base.ExportedMethods != 2 || c.Head.ExportedMethods != 1 || c.Delta.ExportedMethods != -1 || c.Delta.PrivateMethods != 0 {
		t.Fatalf("Container = %+v", c)
	}
	h := rows["p.hooks"]
	if h.Status != "changed" || h.Base.ExportedMethods != 2 || h.Head.ExportedMethods != 4 || h.Delta.ExportedMethods != 2 {
		t.Fatalf("hooks = %+v", h)
	}
	if rows["p.Handle"].Status != "removed" || rows["p.Handle"].Head != nil || rows["p.Handle"].Delta.ExportedMethods != -1 {
		t.Fatalf("Handle = %+v", rows["p.Handle"])
	}
	if rows["p.Gone"].Status != "removed" || rows["p.Gone"].Delta != (delta{Declarations: -1}) {
		t.Fatalf("Gone = %+v", rows["p.Gone"])
	}
	if f := rows["p.Flag"]; f.Status != "introduced" || f.Base != nil || f.Delta.ExportedMethods != 1 || f.Delta.Fields != 1 {
		t.Fatalf("Flag = %+v", f)
	}
	if _, ok := rows["p.Untouched"]; ok {
		t.Fatal("an owner with equal counts must not be reported, even when it moved between files")
	}
	if len(report.Owners) != 5 {
		t.Fatalf("owners = %d", len(report.Owners))
	}
	// The package total is reported as well, so a move inside one package
	// shows as the sum it is.
	if len(report.Packages) != 1 || report.Packages[0].Delta.ExportedMethods != 1 {
		t.Fatalf("packages = %+v", report.Packages)
	}
	if h.Head.Locations[0] != "p/other.go:3" || h.Base.Locations[0] != "p/container.go:9" {
		t.Fatalf("locations: %v %v", h.Head.Locations, h.Base.Locations)
	}
}

